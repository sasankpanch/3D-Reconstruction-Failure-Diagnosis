"""Collect paper-ready metrics from all stages into outputs/PIPELINE_RESULTS.md and outputs/pipeline_results.json.
aerodiag-summary [--data configs/data.yaml]"""
from __future__ import annotations
import argparse, json
from pathlib import Path
import numpy as np, pandas as pd
from ..config import load_config

def _j(p):
    return json.loads(Path(p).read_text()) if Path(p).exists() else {}

def _fmt(v, nd=3):
    if isinstance(v, (list, tuple)) and len(v) == 2:
        return f"[{_fmt(v[0], nd)}, {_fmt(v[1], nd)}]"
    try:
        return "—" if v is None or (isinstance(v, float) and not np.isfinite(v)) else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))
    except Exception:
        return str(v)

def table(rows, cols, headers=None):
    h = headers or cols
    out = ["| " + " | ".join(h) + " |", "|" + "---|" * len(h)]
    for r in rows:
        out.append("| " + " | ".join(_fmt(r.get(c)) for c in cols) + " |")
    return "\n".join(out)

def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--data", default="configs/data.yaml"); a = ap.parse_args(argv)
    cfg = load_config(a.data); O = Path(cfg["root"]) / cfg["paths"]["outputs"]; R = {}; md = ["# Pipeline results (auto-generated by `aerodiag-summary`)", ""]
    A = _j(O / "track_a" / "results.json"); B = _j(O / "track_b" / "results.json"); S2 = _j(O / "step2" / "results.json"); S3 = _j(O / "step3" / "results.json")
    # ---------------- ground truth
    if A:
        R["ground_truth"] = dict(cells_gt=A["stats"]["cells_gt"], cells_gt_good=A.get("stats_gt_good", {}).get("overall", {}).get("cells"),
                                 global_offset_terra_minus_lidar_m=A["align"]["global_offset_pre_alignment"]["median_terra_minus_lidar_stable"],
                                 icp_residual_stable_m=A["align"]["abs_residual_on_stable_after_median"],
                                 sanity_between_frame_spread_m=A["sanity"]["50_consecutive_keyframes"]["between_frame_spread_median_m"],
                                 gt_uncertainty_iqr_median_m=A["stats"]["gt_uncertainty"]["median"])
        md += ["## 1. Ground truth (Track A)", "", table([R["ground_truth"]], list(R["ground_truth"].keys())), ""]
        bc = A.get("stats_gt_good", {}).get("by_class", {})
        rows = [dict(cls=k, **v) for k, v in bc.items() if k in ("airstrip", "paved_motor_road", "roof", "car_park", "green_field", "background")]
        md += ["Label (Terra − LiDAR) on reliable-GT cells, by class (m):", "", table(rows, ["cls", "cells", "median", "abs_p50", "abs_p90", "frac_abs_gt_0_5"]), ""]
    # ---------------- noise floor
    tb = O / "track_b" / "noise_floor_by_group_source_pairs.csv"
    if tb.exists():
        T = pd.read_csv(tb); T = T[(T.group == "healthy_a") & T.source.isin(["terra", "terra+ref", "rtk", "rtk+ref", "noisy_gnss+ref"])]
        piv = T.pivot(index="pairs", columns="source", values="p90").round(2)
        R["noise_floor_p90_px"] = piv.reset_index().to_dict("records")
        md += ["## 2. Across-epipolar noise floor on healthy ground (Track B, |across| p90 in px)", "", "```", piv.to_string(), "```", ""]
        sw = pd.read_csv(O / "track_b" / "sweep_position_noise.csv").pivot(index="pos_sigma_m", columns="pairs", values="p90").round(2)
        R["required_pose_quality_p90_px"] = sw.reset_index().to_dict("records")
        md += ["Position-noise sweep (refined rotation, 0.1° attitude; |across| p90 px):", "", "```", sw.to_string(), "```", ""]
    # ---------------- step 2
    if S2.get("evaluate"):
        E = S2["evaluate"]; R["step2"] = dict(sweep=S2.get("sweep"), height_offset_m=E.get("height_offset_vs_lidar_m"))
        md += ["## 3. Step 2: epipolar search and signals", "", f"Sweep: {S2.get('sweep')}. Global height offset vs LiDAR: {_fmt(E.get('height_offset_vs_lidar_m'))} m (removed below).", "",
               "Height from the 1-D search vs LiDAR on flat paved cells:", "",
               table(E["height_vs_lidar"], ["grp", "n", "abs_dz_p50", "abs_dz_p90", "predicted_sigma_z", "px_per_m"]), "",
               "Plane-sweep across residual on flat paved cells (px):", "", table(E["across_noise_floor_paved"], ["grp", "n", "p50", "p90", "p99"]), "",
               "Signals by class (within-line gaps 5–40):", "",
               table(E["signals_by_class"], ["cls", "rows", "textureless_frac", "across_px_p50", "cost_min_p50", "sharpness_p50", "multi_minima_frac", "periodic_frac", "below_terrain_frac"]), "",
               f"Glint: {E.get('glint')}", ""]
        R["step2"]["height_vs_lidar"] = E["height_vs_lidar"]; R["step2"]["across_noise_floor_paved"] = E["across_noise_floor_paved"]
    # ---------------- step 3
    if S3:
        R["step3"] = dict(label_counts=S3["label_counts"], cv_metrics=S3["cv_metrics"], ablation=S3["ablation_auroc"])
        rows = [dict(head=k, **v) for k, v in S3["cv_metrics"].items()]
        md += ["## 4. Step 3: diagnosis (spatial 5-fold CV, 25 m blocks; 95% CI by block bootstrap)", "",
               table(rows, ["head", "n", "positives", "base_rate", "auroc", "auroc_ci95", "ap", "ap_ci95", "recall_at_5pct_fpr", "brier"]), ""]
        for head in S3["cv_metrics"]:
            rows = [dict(model="full classifier", **S3["cv_metrics"][head])]
            rows += [dict(model=f"baseline: {k}", **v) for k, v in S3["baselines"][head].items()]
            rows += [dict(model=f"physics score: {k}", **v) for k, v in S3["physics_scores"][head].items()]
            md += [f"### Head `{head}`: model vs baselines", "", table(rows, ["model", "auroc", "auroc_ci95", "ap", "recall_at_5pct_fpr"]), ""]
        if "failure_by_stratum" in S3:
            rows = [dict(stratum=k, **v) for k, v in S3["failure_by_stratum"].items()]
            rows.append(dict(stratum="BASELINE: semantic class only (vegetation indicator from LiDAR labels)", **S3["failure_class_only_baseline"]))
            md += ["### Failure head within class strata (confound check)", "", table(rows, ["stratum", "n", "positives", "base_rate", "auroc", "auroc_ci95", "ap", "recall_at_5pct_fpr"]), ""]
            R["step3"]["failure_by_stratum"] = S3["failure_by_stratum"]; R["step3"]["failure_class_only_baseline"] = S3["failure_class_only_baseline"]
        full = {k: v["auroc"] for k, v in S3["cv_metrics"].items()}
        rows = [dict(ablation=k, **{f"{h}_auroc": v.get(h) for h in ("failure", "layered", "water")},
                     **{f"{h}_delta": (v.get(h) - full[h]) if v.get(h) is not None and full.get(h) is not None else None for h in ("failure", "layered", "water")})
                for k, v in S3["ablation_auroc"].items()]
        md += ["### Signal-group ablation (AUROC when the group is removed; delta vs full)", "",
               table(rows, ["ablation", "failure_auroc", "failure_delta", "layered_auroc", "layered_delta", "water_auroc", "water_delta"]), ""]
    (O / "pipeline_results.json").write_text(json.dumps(R, indent=2, default=float)); (O / "PIPELINE_RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))

if __name__ == "__main__":
    main()
